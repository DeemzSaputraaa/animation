import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
const executablePath = process.env.CHROME_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe', '/usr/bin/chromium', '/usr/bin/google-chrome'].find(existsSync);
const browser = await chromium.launch({ executablePath, headless: true });
await mkdir('artifacts', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:3000', { waitUntil: 'domcontentloaded', timeout: 120000 });
  await page.waitForSelector('.preview-panel[data-ready="true"]', { timeout: 90000 });
  await page.screenshot({ path: 'artifacts/studio-ready.png', fullPage: true });
  console.log('GLB loaded; initial render captured.');
  await page.locator('#script').fill('Selamat datang. Hari ini kita belajar kecerdasan buatan. Perhatikan bagian yang sangat penting ini. Bagaimana kita dapat menggunakannya dengan bijak?');
  await page.getByRole('button', { name: 'Generate Performance' }).click();
  await page.waitForFunction(() => !document.querySelector('.play-button').disabled || !!document.querySelector('.error-box'), null, { timeout: 180000 });
  assert.equal(await page.locator('.error-box').count(), 0, await page.locator('.error-box').allTextContents());
  const timelineUrl = await page.getByRole('link', { name: 'Unduh timeline' }).getAttribute('href');
  const timeline = await (await page.request.get(new URL(timelineUrl, page.url()).href)).json();
  assert(timeline.duration > 0 && timeline.visemes.length > 20 && timeline.gestures.length > 1);
  console.log(JSON.stringify({ duration: timeline.duration, gestures: timeline.gestures.length, visemes: timeline.visemes.length, emotions: timeline.emotion.map(item => item.emotion) }));
  // Inspect the strongest part of a hand gesture in the full-body view.
  const handGesture = timeline.gestures.find(event => event.duration >= 1.5) ?? timeline.gestures[0];
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.locator('.seek input').fill((handGesture.start + handGesture.duration * .5).toFixed(2));
  await page.screenshot({ path: 'artifacts/studio-hands.png', fullPage: true });
  await page.getByRole('button', { name: 'Stop', exact: true }).click();
  await page.getByRole('button', { name: 'Fokus wajah', exact: false }).click();
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector('.seek input').value) > 1, null, { timeout: 15000 });
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  const paused = Number(await page.locator('.seek input').inputValue());
  await page.waitForTimeout(500);
  assert(Math.abs(Number(await page.locator('.seek input').inputValue()) - paused) < .05, 'Pause must freeze the audio master clock');
  await page.screenshot({ path: 'artifacts/studio-paused.png', fullPage: true });
  await page.locator('.seek input').fill(String(Math.min(4, timeline.duration / 2)));
  await page.getByRole('button', { name: 'Lanjutkan pemutaran' }).click();
  await page.waitForTimeout(500);
  await page.getByRole('button', { name: 'Stop', exact: true }).click();
  assert.equal(Number(await page.locator('.seek input').inputValue()), 0);
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForSelector('.status-pill.finished', { timeout: Math.ceil(timeline.duration * 1000) + 15000 });
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('Generate / Play / Pause / seek / Stop / replay / finish passed; no browser errors.');
  await page.screenshot({ path: 'artifacts/studio-finished.png', fullPage: true });
} finally { await browser.close(); }
